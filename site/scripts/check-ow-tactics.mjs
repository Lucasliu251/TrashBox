import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import ts from 'typescript'
const base = new URL('../src/features/ow/', import.meta.url)
const source = async name => await readFile(new URL(name, base), 'utf8')
const compiled = text => ts.transpileModule(text, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
const counterUrl = 'data:text/javascript;base64,' + Buffer.from(compiled(await source('tactics-counter-table.ts'))).toString('base64')
const dataUrl = 'data:text/javascript;base64,' + Buffer.from(compiled(await source('tactics-data.ts'))).toString('base64')
const engineSource = compiled(await source('tactics.ts')).replace(/from ['"]\.\/tactics-data['"]/g, `from ${JSON.stringify(dataUrl)}`)
const sourcedEngine = engineSource.replace(/from ['"]\.\/tactics-counter-table['"]/g, `from ${JSON.stringify(counterUrl)}`)
const engine = await import('data:text/javascript;base64,' + Buffer.from(sourcedEngine).toString('base64'))
const catalog = JSON.parse(await readFile(new URL('../public/ow-data/catalog.json', import.meta.url), 'utf8'))
const snapshot = JSON.parse(await readFile(new URL('../public/ow-data/jingji-5-all.json', import.meta.url), 'utf8'))
const roster = engine.tacticalRoster(catalog.heroes, snapshot.rows)
const byId = new Map(roster.map(hero => [hero.id, hero]))
const original = JSON.stringify(roster)
const edges = engine.matchups(roster)
assert(edges.length > 0)
assert(edges.every(edge => edge.from !== edge.to && byId.has(edge.from) && byId.has(edge.to)))
assert(edges.every(edge => edge.reasons.every(reason => reason.condition && reason.sourceIds.length)))
assert.equal(edges.find(edge => edge.from === 'zarya' && edge.to === 'dva').rating,8)
assert(!edges.some(edge => edge.from === 'dva' && edge.to === 'zarya'))
assert.equal(new Set(edges.map(edge => edge.from + ':' + edge.to)).size, edges.length)
assert(edges.every(edge => edge.sourceUrls.length && edge.rating > 5 && edge.rating <= 10))
assert.equal(roster.filter(hero=>hero.assessed).length,51)
assert(edges.length < 545)
assert(!edges.some(edge=>['sombra','roadhog'].includes(edge.from)||['sombra','roadhog'].includes(edge.to)))
const unsupported = roster.find(hero => hero.id === 'doctrine')
assert(unsupported)
assert(!edges.some(edge => edge.from === unsupported.id || edge.to === unsupported.id))
assert(engine.matchesHero(byId.get('winston'), '猩猩'))
assert(engine.matchesHero(byId.get('soldier-76'), '76'))
assert.deepEqual(engine.parseHeroList(roster, '猩猩，源氏,法鸡；安娜\n天使').ids, ['winston','genji','pharah','ana','mercy'])
assert(engine.parseHeroList(roster, 'D.VA，dva').issues.some(issue=>issue.includes('重复')))
assert(engine.parseHeroList(roster, '不存在的英雄').issues.length)
assert(engine.parseHeroList(roster, '源氏,猎空,安娜,天使,雾子,76').issues.length)
assert.equal(engine.tacticalRoster([{...byId.get('sombra'),catalogRole:'3'}], [{heroId:'sombra',role:'1'}])[0].role, '3')
assert.deepEqual(engine.recommendTeams(roster, [], []), [])
assert.deepEqual(engine.recommendTeams(roster, ['not-a-hero'], []), [])
assert(engine.validateTeams(roster, ['genji', 'genji'], []).some(issue => issue.includes('重复')))
assert(engine.validateTeams(roster, [], ['dva', 'winston']).some(issue => issue.includes('超出')))
assert(engine.validateTeams(roster, [], ['genji','tracer','reaper']).some(issue => issue.includes('超出')))
assert.deepEqual(engine.recommendTeams(roster, [], ['dva','winston']), [])
const enemy = ['winston','genji','pharah','ana','mercy']
const locked = ['dva','kiriko']
const beforeEnemy = JSON.stringify(enemy), beforeOwn = JSON.stringify(locked)
const start = performance.now()
const suggestions = engine.recommendTeams(roster, enemy, locked)
assert(suggestions.length > 0)
assert(suggestions[0].coverage.includes('pharah'), 'Avoid stacking beam responses to Genji while ignoring an airborne threat')
function valid(team, required) {
 assert.equal(team.ids.length,5)
 assert.equal(new Set(team.ids).size,5)
 assert(required.every(id=>team.ids.includes(id)))
 assert.equal(team.ids.filter(id=>byId.get(id).role==='2').length,1)
 assert.equal(team.ids.filter(id=>byId.get(id).role==='1').length,2)
 assert.equal(team.ids.filter(id=>byId.get(id).role==='3').length,2)
 assert(Number.isFinite(team.score))
}
for (const team of suggestions) valid(team,locked)
assert.equal(JSON.stringify(enemy),beforeEnemy);assert.equal(JSON.stringify(locked),beforeOwn);assert.equal(JSON.stringify(roster),original)
const almostFull = ['dva','genji','soldier-76','ana']
const oneSlot = engine.recommendTeams(roster,enemy,almostFull)
assert.equal(oneSlot.length,3,'Single-slot fills should offer alternative supports')
for(const team of oneSlot)valid(team,almostFull)
const full = ['dva','genji','soldier-76','ana','kiriko']
assert.deepEqual(new Set(engine.recommendTeams(roster,enemy,full)[0].ids),new Set(full))
const unknown = engine.recommendTeams(roster,[unsupported.id],['dva'])
assert(unknown.length)
assert(unknown.every(team=>team.unknownEnemies.includes(unsupported.id) && !team.coverage.includes(unsupported.id)))
if(unsupported.role) {
 const ownUnknown = engine.recommendTeams(roster,enemy,[unsupported.id])
 assert(ownUnknown.length);for(const team of ownUnknown)valid(team,[unsupported.id])
}
assert.deepEqual(engine.recommendTeams(roster,enemy,[],0),[])
console.log(`OW tactics passed: ${roster.length} searchable heroes, ${roster.filter(hero=>hero.assessed).length} sourced heroes, ${edges.length} directed community relations; role limits, locks, unknowns, aliases, symmetry and single-slot alternatives checked. Sample compute ${(performance.now()-start).toFixed(0)}ms.`)
